/**
 * Finds a theme by identifier.
 *
 * @param id - Identifier such as `monokai`.
 * @returns The theme, or `undefined` when no theme has that identifier.
 */
export function findTheme(id: string): ThemeDefinition | undefined {
  return themes.find((theme) => theme.id === id)
}
